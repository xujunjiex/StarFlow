package com.moe.starflow.sr

/**
 * **超分该用几个线程**（用户口径 2026-10：「自动根据手机性能决定用几核，8 核就用 6 核」）。
 *
 * ```
 * 线程 = 核数 - 2   （钳在 2..8）
 * ```
 * 留 2 个核给前台（UI / OCR / 手势），手机不至于卡死。真机实测（Redmi 2407FRK8EC，8 核，
 * AnimeJaNai Balanced 640×960→2x）：
 *
 * | 线程 | 最小耗时 | 备注 |
 * |---|---|---|
 * | 4 | 2237 ms | |
 * | **6** | **1981 ms** | 只比满核慢 13%，但前台还有余量 |
 * | 8 | 1758 ms | 最快，但 `loadavg` 冲到 35，**手机没法用**（用户实测抱怨） |
 *
 * ⚠️ 不要写死 8：4 核机器上写死 8 只会互相抢核，可能比 2 线程还慢。
 * ⚠️ 产品路径与基准工具**共用这一个函数**，避免两处策略漂移。
 */
internal fun srThreads(): Int =
    (Runtime.getRuntime().availableProcessors() - 2).coerceIn(2, 8)
